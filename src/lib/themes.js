export function getThemeById(id) {
  return THEMES.find((theme) => theme.id === id) || THEMES[0];
}

export function getThemeVars(theme) {
  return {
    "--tt-accent": theme.accent,
    "--tt-accent-2": theme.accent2,
    "--tt-accent-hover": `${theme.accent}cc`,
    "--tt-accent-soft": `color-mix(in srgb, ${theme.accent} 14%, transparent)`,
    "--tt-accent-strong": `color-mix(in srgb, ${theme.accent} 84%, white)`,
    "--tt-bg": theme.bg,
    "--tt-rail": theme.rail,
    "--tt-surface": theme.surface,
    "--tt-surface-elevated": theme.elevated,
    "--tt-surface-hover": theme.hover,
    "--tt-border": `color-mix(in srgb, ${theme.accent} 8%, rgba(255, 255, 255, 0.05))`,
    "--tt-divider": `color-mix(in srgb, ${theme.accent} 12%, rgba(255, 255, 255, 0.06))`,
    "--tt-page-start": theme.pageStart,
    "--tt-hero-start": theme.heroStart,
    "--tt-hero-mid": theme.heroMid,
    "--tt-hero-end": theme.heroEnd,
  };
}